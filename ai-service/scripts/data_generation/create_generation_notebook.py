            "def prior_mastery(history: list[dict], skill: str) -> float:\n",
            "    \"\"\"Ước lượng độ thành thạo trước đó của học viên trên kỹ năng (Laplace Smoothing).\"\"\"\n",
            "    outcomes = [row[\"is_correct\"] for row in history if row[\"skill_id\"] == skill]\n",
            "    return (sum(outcomes) + 1) / (len(outcomes) + 2) if outcomes else 0.35\n",
            "\n",
            "def generate_learner(\n",
            "    language: str, learner_number: int, persona: str, order: list[str],\n",
            "    parents: dict[str, tuple[str, ...]], items_by_skill: dict[str, list[dict]],\n",
            "    rng: random.Random,\n",
            ") -> list[dict]:\n",
            "    \"\"\"Sinh toàn bộ chuỗi lịch sử làm bài cho 1 học viên cụ thể.\"\"\"\n",
            "    cfg = PERSONAS[persona]\n",
            "    user_id = f\"syn_{language}_{persona.lower()}_{learner_number:02d}\"\n",
            "    ability = rng.gauss(cfg[\"ability\"], 0.32)\n",
            "    learning = max(0.15, rng.gauss(cfg[\"learning\"], 0.08))\n",
            "    misconception = {skill: rng.uniform(0.25, 0.75) for skill in rng.sample(order, k=4)}\n",
            "    history: list[dict] = []\n",
            "    exposure: Counter[str] = Counter()\n",
            "    last_seen: dict[str, datetime] = {}\n",
            "    \n",
            "    # Phân bổ ngày bắt đầu trong 3 - 6 tháng gần nhất (tháng 3/2026 -> 10/2026)\n",
            "    current = datetime(2026, 3, 1, 9, 0) + timedelta(\n",
            "        days=rng.randrange(0, 110), hours=rng.randrange(0, 12), minutes=rng.randrange(0, 60)\n",
            "    )\n",
            "    session_length = rng.randrange(6, 12)\n",
            "    total_steps = rng.randrange(95, 125) if language == \"python\" else rng.randrange(52, 76)\n",
            "    retry_item: tuple[str, dict, int] | None = None\n",
            "\n",
            "    for step in range(1, total_steps + 1):\n",
            "        # Khoảng cách giữa các buổi học (session)\n",
            "        if step > 1 and (step - 1) % session_length == 0:\n",
            "            current += timedelta(days=rng.choice((1, 1, 2, 2, 3, 4, 7)), hours=rng.randrange(0, 6))\n",
            "            if current.hour < 8:\n",
            "                current = current.replace(hour=8 + rng.randrange(0, 4))\n",
            "            elif current.hour >= 23:\n",
            "                current = (current + timedelta(days=1)).replace(hour=9 + rng.randrange(0, 3))\n",
            "            session_length = rng.randrange(6, 12)\n",
            "\n",
            "        if retry_item is not None:\n",
            "            skill, item, attempt_index = retry_item\n",
            "            retry_item = None\n",
            "        else:\n",
            "            seen = [s for s in order if exposure[s] > 0]\n",
            "            frontier = [s for s in order if exposure[s] == 0 and all(exposure[p] > 0 for p in parents[s])]\n",
            "\n",
            "            # 4% cơ hội tò mò nhảy cóc bài nâng cao (Curiosity / Anomaly)\n",
            "            if rng.random() < 0.04 and len(order) > len(seen) + 2:\n",
            "                candidates = order[min(len(order) - 1, len(seen) + 1):min(len(order), len(seen) + 5)]\n",
            "                skill = rng.choice(candidates) if candidates else order[0]\n",
            "            elif seen and (not frontier or rng.random() < 0.27):\n",
            "                skill = rng.choice(seen[-min(9, len(seen)):])  # Ôn tập kỹ năng cũ (Spaced Review)\n",
            "            elif frontier:\n",
            "                skill = rng.choice(frontier[:min(4, len(frontier))])  # Khám phá kỹ năng mới ở biên\n",
            "            else:\n",
            "                skill = order[0]\n",
            "            item = rng.choice(items_by_skill[skill])\n",
            "            attempt_index = 1\n",
            "\n",
            "        difficulty = int(item[\"difficulty\"])\n",
            "\n",
            "        # Tính toán xác suất thành công IRT\n",
            "        prior = [prior_mastery(history, p) for p in parents[skill]]\n",
            "        prereq_proxy = sum(prior) / len(prior) if prior else 1.0\n",
            "        days_away = (current - last_seen[skill]).total_seconds() / 86400 if skill in last_seen else 0.0\n",
            "        forgetting = min(0.65, 0.16 * math.log1p(days_away)) if exposure[skill] else 0.0\n",
            "        transfer = 0.26 if persona == \"RETURNING\" and skill in order[:max(3, len(order) // 4)] else 0.0\n",
            "        retry_gain = 0.40 if attempt_index > 1 else 0.0\n",
            "        score = (\n",
            "            ability + transfer + learning * math.log1p(exposure[skill]) + retry_gain\n",
            "            - 0.43 * (difficulty - 1) - 0.23 * (exposure[skill] == 0)\n",
            "            - forgetting - misconception.get(skill, 0.0)\n",
            "        )\n",
            "        probability = min(0.89, max(0.12, 0.08 + 0.84 / (1 + math.exp(-score))))\n",
            "\n",
            "        # Bổ sung nhiễu ngẫu nhiên (Noise/Anomalies)\n",
            "        anomaly_roll = rng.random()\n",
            "        if anomaly_roll < 0.04:\n",
            "            probability = min(0.92, probability + 0.38)  # Đoán mò may mắn\n",
            "        elif anomaly_roll < 0.08:\n",
            "            probability = max(0.08, probability - 0.42)  # Sơ suất/lỗi gõ ở bài dễ\n",
            "\n",
            "        correct = int(rng.random() < probability)\n",
            "        if correct:\n",
            "            error = \"NONE\"\n",
            "        else:\n",
            "            error = rng.choices(\n",
            "                (LANGUAGE_MISTAKES[language].get(skill, \"WRONG_ANSWER\"), \"WRONG_ANSWER\", \"SYNTAX_ERROR\"),\n",
            "                weights=(5, 3, 2), k=1,\n",
            "            )[0]\n",
            "\n",
            "        # Cân chỉnh thời gian làm bài thực tế (Log-Normal)\n",
            "        if difficulty == 1:\n",
            "            base_seconds = 115.0 + (45.0 if exposure[skill] == 0 else 0.0)\n",
            "        elif difficulty == 2:\n",
            "            base_seconds = 285.0 + (65.0 if exposure[skill] == 0 else 0.0)\n",
            "        else:\n",
            "            base_seconds = 580.0 + (110.0 if exposure[skill] == 0 else 0.0)\n",
            "\n",
            "        if attempt_index > 1 and persona in (\"TRIAL_ERROR\", \"NEW\") and rng.random() < 0.05:\n",
            "            seconds = max(10.0, round(rng.uniform(12.0, 35.0), 1))  # Spam nộp lại nhanh\n",
            "        else:\n",
            "            seconds = max(30.0, round(rng.lognormvariate(math.log(base_seconds), 0.35), 1))\n",
            "            if persona == \"STEADY\":\n",
            "                seconds = round(seconds * 1.25, 1)\n",
            "            elif persona == \"FAST\":\n",
            "                seconds = round(seconds * 0.75, 1)\n",
            "            elif persona == \"NEW\":\n",
            "                seconds = round(seconds * 1.15, 1)\n",
            "\n",
            "        current += timedelta(seconds=seconds + rng.randrange(25, 115))\n",
            "        history.append({\n",
            "            \"user_id\": user_id, \"persona_group\": persona, \"step_index\": step,\n",
            "            \"timestamp\": current.isoformat(), \"language\": language, \"skill_id\": skill,\n",
            "            \"item_id\": item[\"item_id\"], \"item_title\": item[\"item_title\"],\n",
            "            \"lesson_code\": item[\"lesson_code\"], \"item_source\": item[\"item_source\"],\n",
            "            \"difficulty\": difficulty, \"is_correct\": correct, \"attempt_index\": attempt_index,\n",
            "            \"time_taken_seconds\": seconds,\n",
            "            \"error_type\": error, \"prereq_mastery_proxy\": round(prereq_proxy, 4),\n",
            "        })\n",
            "        exposure[skill] += 1\n",
            "        last_seen[skill] = current\n",
            "        if not correct and attempt_index < 3 and rng.random() < cfg[\"persistence\"]:\n",
            "            retry_item = (skill, item, attempt_index + 1)\n",
            "            \n",
            "    return history"
